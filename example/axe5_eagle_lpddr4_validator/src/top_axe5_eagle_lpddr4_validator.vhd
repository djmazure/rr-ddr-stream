-------------------------------------------------------------------------------
-- top_axe5_eagle_lpddr4_validator
--
-- Arrow AXE5-Eagle (Agilex 5 E-Series SoC, A5ED065BB32AE4SR0).
--
-- Exercises ddr_stream_axi against the board's FABRIC LPDDR4 device (1 GB,
-- controller emif_bank2a_fpga, 256-bit AXI4). The test data path stays in the
-- fabric:
--
--   ddr_validator_bist -> ddr_stream_axi -> emif_bank2a_fpga -> LPDDR4
--   LPDDR4 -> emif_bank2a_fpga -> ddr_stream_axi -> ddr_validator_bist
--
-- Linux on the HPS starts a run and reads the verdict through the
-- lightweight HPS-to-FPGA bridge (lwhps2fpga) and ddr_validator_csr.
--
-- hps_subsys is generated by rr from ip.yml (rr synth run). It provides:
--   h2f_user0_clk : the fabric clock. The board has no free-running fabric
--                   oscillator, so the HPS clock is looped back into
--                   fabric_clk and used as clk_sys.
--   ninit_done    : high until device configuration is complete.
--   lwhps2fpga    : AXI master, CSR access from Linux.
--   emif_*        : the HPS's own LPDDR4 (Linux memory), not the device
--                   under test.
--   f2sdram_*     : FPGA-to-HPS-SDRAM bridge. Enabled in the frozen HPS
--                   component, unused here: no transaction is ever issued.
-------------------------------------------------------------------------------

